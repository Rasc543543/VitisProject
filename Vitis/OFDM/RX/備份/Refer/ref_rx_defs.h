// ==========================================
// Helper Functions (IQ 封裝與轉換)
// ==========================================
static inline half u16_to_half(ap_uint<16> d)
{
    half h;
    uint16_t tmp = d.to_uint();
    memcpy(&h, &tmp, 2); // ✅ 使用 memcpy 避開編譯器指標崩潰
    return h;
}

static inline ap_uint<16> half_to_u16(half h)
{
    uint16_t tmp;
    memcpy(&tmp, &h, 2); // ✅ 使用 memcpy 避開編譯器指標崩潰
    return ap_uint<16>(tmp);
}

// ✅ 【新增】將硬體傳來的 16-bit 定點數，除以 2048 還原成浮點數
static inline half fixed16_to_half(ap_uint<16> d)
{
    // 1. 強制轉成有號整數 int16_t，保留正負號與數值
    int16_t fixed_val = (int16_t)d.to_uint();
    // 2. 除以 2048.0f，還原小數點，並轉成 half
    return (half)((float)fixed_val / 2048.0f);
}

// ✅ 【新增】Testbench 模擬硬體 FFT 輸出打包用
static inline ap_uint<32> pack_int16(int16_t i, int16_t q)
{
    ap_uint<32> v;
    v(15, 0) = (uint16_t)i;
    v(31, 16) = (uint16_t)q;
    return v;
}

// 統一的 Packed 封裝邏輯: Q 放在高位, I 放在低位
static inline ap_uint<32> pack_iq(half i, half q)
{
#pragma HLS INLINE
    ap_uint<32> v;
    v(15, 0) = half_to_u16(i);
    v(31, 16) = half_to_u16(q);
    return v;
}

